import numpy as np
import torch
import logging


ArrayLike = Union[np.ndarray, "list[float]", "tuple[float]"]

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)

def _as_2d(x: ArrayLike) -> np.ndarray:
    """Ensure input is 2D: (N, D)."""
    x = np.asarray(x)
    if x.ndim == 1:
        return x[None, :]
    if x.ndim != 2:
        raise ValueError(f"_as_2d expects 1D or 2D array, got shape {x.shape}")
    return x


def _add_diag(cov: ArrayLike, bias: float) -> np.ndarray:
    """
    Add `bias` to the diagonal for numeric stability.

    support：
    - (D,)         : diagonal vector
    - (D, D)       : Single covariance
    - (B, D, D)    : batch covariance
    """
    cov = np.asarray(cov, dtype=np.float64)

    if bias <= 0.0:
        return cov

    if cov.ndim == 1:
        return np.clip(cov, bias, None)

    if cov.ndim == 2:
        d = cov.shape[-1]
        cov = cov.copy()
        cov[np.arange(d), np.arange(d)] += bias
        return cov

    if cov.ndim == 3:
        b, d, d2 = cov.shape
        if d != d2:
            raise ValueError(f"Expected cov of shape (B,D,D), got {cov.shape}")
        cov = cov.copy()
        idx = np.arange(d)
        cov[:, idx, idx] += bias
        return cov

    raise ValueError(f"Unsupported covariance shape: {cov.shape}")


def _normalize(x: ArrayLike, eps: float = 1e-12) -> np.ndarray:
    """L2-normalize along the last dimension."""
    x = np.asarray(x, dtype=np.float64)
    norm = np.linalg.norm(x, axis=-1, keepdims=True)
    return x / (norm + eps)


def MAP_estimation_semantic(
    support_semantic: Optional[ArrayLike],
    support_image: ArrayLike,
    base_semantic: Optional[ArrayLike],
    base_means: ArrayLike,
    base_cov: ArrayLike,
    topk: int = 5,
    Estimate_COV: bool = False,
    alpha: float = 0.33,
    beta: float = 0.9,
    cov_bias: float = 0.01,
    use_semantic: bool = False,
    support_weights: Optional[ArrayLike] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    MAP estimates the (mu_s, Sigma_s) of the novel class.

    support_image: (D,) / (n_shot, D)
    base_means   : (N_base, D)
    base_cov     : (N_base, D, D) / (N_base, D) , The final average will be calculated over the top-k values.
    """
    support_image = np.asarray(support_image, dtype=np.float64)
    sigma_self = None

   
    if support_image.ndim == 2:
        # (n_shot, D)
        if Estimate_COV:
            # rowvar=False -> Calculate covariance by column
            sigma_self = np.cov(support_image, rowvar=False)

        if support_weights is not None:
            w = np.asarray(support_weights, dtype=np.float64)
            w = w / (w.sum() + 1e-12)
            support_image = (support_image * w[:, None]).sum(axis=0)
        else:
            support_image = support_image.mean(axis=0)
    elif support_image.ndim != 1:
        raise ValueError(
            f"support_image must be (D,) or (n_shot,D), got {support_image.shape}"
        )

    # ---- selecy top-k from Base  ----
    base_means_2d = _as_2d(base_means)
    n_base = base_means_2d.shape[0]
    topk = max(1, min(int(topk), n_base))

    if use_semantic and (support_semantic is not None) and (base_semantic is not None):
        # Semantic space cosine distance
        s = np.asarray(support_semantic, dtype=np.float64)
        s = s.mean(axis=0) if s.ndim == 2 else s
        b = np.asarray(base_semantic, dtype=np.float64)
        s_n = _normalize(s)[None, :]
        b_n = _normalize(b)
        sim = (b_n * s_n).sum(axis=-1)
        dist = -sim
    else:
        # Visual Space   L2
        diff = base_means_2d - support_image[None, :]
        dist = np.sum(diff ** 2, axis=-1)

    index = np.argpartition(dist, topk - 1)[:topk]

    # Base proir --> mean / cov
    mu_p = base_means_2d[index].mean(axis=0)
    base_cov_arr = np.asarray(base_cov, dtype=np.float64)
    sigma_p_mean = base_cov_arr[index].mean(axis=0)

   
    alpha_eff, beta_eff = float(alpha), float(beta)
    

    # ---- posteriori ----
    mu_s = alpha_eff * support_image + (1.0 - alpha_eff) * mu_p
    if Estimate_COV and (sigma_self is not None):
        sigma_s = beta_eff * sigma_self + (1.0 - beta_eff) * sigma_p_mean
    else:
        sigma_s = sigma_p_mean

    sigma_s = _add_diag(sigma_s.astype(np.float64), cov_bias)
    return mu_s.astype(np.float64), sigma_s

def get_semantic_dataset_name(args):
    """
    Map dataset argument to the prefix used in semantic filenames.
    """
    d_name = args.dataset.lower()
    if 'miniimagenet' in d_name:
        return 'miniimagenet'
    elif 'tiered' in d_name:
        return 'tieredimagenet' # Ensure consistency with the output generated by build_caption_semantic.py
    elif 'fc100' in d_name:
        return 'fc100'
    elif 'cifar' in d_name:
        return 'cifar_fs' # Or 'cifar100', depending on the name of your generated file.
    else:
        return d_name

def load_base_stats_for_map(args, base_dir=None,log=None):
    """
    Load base class statistics (mean/cov) for MAP.
    Supports generic dataset loading.
    """
    if base_dir is None: base_dir = BASE_DIR
    
    # Generic filename construction
    center_filename = f"center_{args.dataset}_{args.backbone}.pth"
    center_path = os.path.join(base_dir, center_filename)

    if not os.path.exists(center_path):
        raise FileNotFoundError(f"[MAP] Base stats file not found: {center_path}")
    
    log.info(f"[MAP] Using base stats file: {center_path}")

    center_dict = torch.load(center_path, map_location="cpu")
    base_mean_dict = center_dict["mean"]
    base_var_dict = center_dict.get("var", center_dict.get("cov", None)) # Try 'var' then 'cov'

    base_class_keys = sorted(base_mean_dict.keys())
    
    base_means = np.stack(
        [np.asarray(base_mean_dict[c], dtype=np.float32) for c in base_class_keys], 
        axis=0
    )

    if base_var_dict is not None:
        base_cov = np.stack(
            [np.diag(np.asarray(base_var_dict[c], dtype=np.float32)) for c in base_class_keys],
            axis=0
        )
    else:
        D = base_means.shape[1]
        base_cov = np.tile(np.eye(D, dtype=np.float32)[None, :, :], (len(base_class_keys), 1, 1))

    class_to_index = {c: i for i, c in enumerate(base_class_keys)}
    return base_means, base_cov, base_class_keys, class_to_index

def load_semantic_for_split(args, split, base_dir=BASE_DIR, map_location="cpu", sem_kind="clsname",log=None):
    """
    Generic semantic loader supporting multiple datasets and semantic kinds.
    """
    dataset_name = get_semantic_dataset_name(args)
    
    # 1. Determine Semantic Filename
    if sem_kind == "imgsem":
        # e.g., imagenet_imgsem_clip_caption_train.pth
        sem_filename = f"{dataset_name}_imgsem_{args.mode}_{args.text_type}_{split}.pth"
    elif sem_kind == "concat":
        # e.g., imagenet_semantic_clip_caption_train.pth (for class-level concat)
        sem_filename = f"{dataset_name}_semantic_{args.mode}_{args.text_type}_{split}.pth"
    elif sem_kind == "clsname":
        # e.g., imagenet_semantic_clsname_clip_caption_train.pth
        sem_filename = f"{dataset_name}_semantic_{sem_kind}_{args.mode}_{args.text_type}_{split}.pth"
    else:
        # Fallback for other class-level semantics like captionavg
        sem_filename = f"{dataset_name}_semantic_{sem_kind}_{args.mode}_{args.text_type}_{split}.pth"

    sem_path = os.path.join(base_dir, "semantic", sem_filename)

    log.info(f"[Semantic][split={split}][kind={sem_kind}] "
        f"using class semantic file: {sem_path}")
    
    if not os.path.exists(sem_path):
        # Fallback logic or error
        raise FileNotFoundError(f"[Semantic] File not found: {sem_path}")

    sem_dict = torch.load(sem_path, map_location=map_location)
    
    # 2. Extract Semantic Feature
    loaded_semantic = None
    if sem_kind == "imgsem":
        # Image level semantics 
        loaded_semantic = sem_dict["img_semantics"]
    elif sem_kind == "clsname":
        # Class name semantic
        loaded_semantic = sem_dict["semantic_class"]
    elif sem_kind == "captionavg":
        # Class-caption average semantic
        loaded_semantic = sem_dict["semantic_caption_avg"]
    elif sem_kind == "concat":
        # Concatenated semantic
        # Try common keys for concat
        keys_to_try = ["semantic_feature", "semantic_concat"]
        for k in keys_to_try:
            if k in sem_dict:
                loaded_semantic = sem_dict[k]
                break
    if loaded_semantic is None:
        raise KeyError(f"Could not find semantic tensor/dict for kind='{sem_kind}' in {sem_path}. Keys: {sem_dict.keys()}")
    
    # 3. Returns: (semantic features, class_to_idx, idx_to_class, None)
    #    Note: The loaded_semantic returned here may be a Dict[str, Tensor] or a Tensor (if it is imgsem).
    return loaded_semantic, sem_dict.get("class_to_idx"), sem_dict.get("idx_to_class"), None 
   
   
    